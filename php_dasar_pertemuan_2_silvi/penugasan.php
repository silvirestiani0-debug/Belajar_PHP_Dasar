<?php

$a = 20;

// Operator Penugasan
$a += 10; // $a sekarang bernilai 30
echo $a . "<br>";

$a -= 5; // $a sekarang bernilai 25
echo $a . "<br>";

$a *= 2; // $a sekarang bernilai 50
echo $a . "<br>";

$a /= 5; // $a sekarang bernilai 10
echo $a . "<br>";

$a %= 3; // $a sekarang bernilai 1
echo $a . "<br>";

?>